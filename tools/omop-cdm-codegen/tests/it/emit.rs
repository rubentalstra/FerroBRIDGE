//! The emitter: what it writes, that it writes the same bytes twice, and that
//! check mode sees a hand edit.

use std::collections::BTreeMap;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use omop_cdm_codegen::emit::{EmitError, EmitOptions, emit};

use crate::definitions::{CSV_DIR, DDL_DIR};

/// The workspace `rustfmt.toml`, so a test formats what the CLI formats.
const RUSTFMT_CONFIG: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../rustfmt.toml");

/// The emit options for a scratch crate directory.
fn options(crate_dir: &Path, check: bool) -> EmitOptions {
    EmitOptions {
        definitions_dir: PathBuf::from(CSV_DIR),
        ddl_dir: PathBuf::from(DDL_DIR),
        crate_dir: crate_dir.to_path_buf(),
        rustfmt_config: PathBuf::from(RUSTFMT_CONFIG),
        check,
    }
}

/// Every file under `root`, keyed by its path relative to it.
fn tree(root: &Path) -> Result<BTreeMap<String, Vec<u8>>, Box<dyn Error>> {
    let mut files = BTreeMap::new();
    collect(root, root, &mut files)?;
    Ok(files)
}

fn collect(
    root: &Path,
    dir: &Path,
    files: &mut BTreeMap<String, Vec<u8>>,
) -> Result<(), Box<dyn Error>> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(root, &path, files)?;
        } else {
            let relative = path.strip_prefix(root)?.to_string_lossy().into_owned();
            files.insert(relative, fs::read(&path)?);
        }
    }
    Ok(())
}

#[test]
fn the_emitter_writes_a_module_per_table_and_the_ddl() -> Result<(), Box<dyn Error>> {
    let scratch = tempfile::tempdir()?;
    let report = emit(&options(scratch.path(), false))?;
    assert_eq!(39, report.columns.len());
    assert_eq!(432, report.columns.values().sum::<usize>());

    let files = tree(scratch.path())?;
    assert!(files.contains_key("src/generated/mod.rs"));
    assert!(files.contains_key("src/generated/person.rs"));
    assert!(files.contains_key("src/generated/ddl.rs"));
    assert!(files.contains_key("ddl/OMOPCDM_postgresql_5.4_ddl.sql"));
    assert!(files.contains_key("ddl/PROVENANCE.md"));
    assert_eq!(
        39 + 2 + 5,
        files.len(),
        "the emitted tree is the 39 table modules, mod.rs and ddl.rs, and the four DDL files with their provenance"
    );
    Ok(())
}

#[test]
fn every_generated_file_carries_the_banner() -> Result<(), Box<dyn Error>> {
    let scratch = tempfile::tempdir()?;
    emit(&options(scratch.path(), false))?;
    for (relative, content) in tree(scratch.path())? {
        if Path::new(&relative).extension() != Some("rs".as_ref()) {
            continue;
        }
        let text = String::from_utf8(content)?;
        assert!(
            text.starts_with(
                "// @generated by omop-cdm-codegen from OHDSI/CommonDataModel v5.4.3. DO NOT EDIT.\n"
            ),
            "{relative} does not open with the generated banner"
        );
        // The banner holds the first line and the SPDX tags follow it (#129).
        assert!(
            text.contains(
                "\n// SPDX-FileCopyrightText: Ruben Talstra\n// SPDX-License-Identifier: BUSL-1.1\n"
            ),
            "{relative} does not carry the SPDX tags under the banner"
        );
    }
    Ok(())
}

#[test]
fn the_emitter_is_byte_deterministic() -> Result<(), Box<dyn Error>> {
    let first = tempfile::tempdir()?;
    let second = tempfile::tempdir()?;
    emit(&options(first.path(), false))?;
    emit(&options(second.path(), false))?;
    assert_eq!(
        tree(first.path())?,
        tree(second.path())?,
        "two runs over the same inputs produced different bytes"
    );
    Ok(())
}

#[test]
fn check_mode_passes_on_a_tree_the_emitter_just_wrote() -> Result<(), Box<dyn Error>> {
    let scratch = tempfile::tempdir()?;
    emit(&options(scratch.path(), false))?;
    emit(&options(scratch.path(), true))?;
    Ok(())
}

#[test]
fn check_mode_reports_a_hand_edit_and_a_stale_file() -> Result<(), Box<dyn Error>> {
    let scratch = tempfile::tempdir()?;
    emit(&options(scratch.path(), false))?;

    let generated = scratch.path().join("src/generated");
    fs::write(generated.join("person.rs"), "// hand edited\n")?;
    fs::write(generated.join("gone.rs"), "// no table lowers to this\n")?;
    fs::write(
        scratch.path().join("ddl/OMOPCDM_postgresql_5.4_views.sql"),
        "-- no vendored file carries this\n",
    )?;

    let Err(EmitError::Drift { paths }) = emit(&options(scratch.path(), true)) else {
        panic!("check mode accepted an edited tree");
    };
    assert_eq!(
        vec![
            String::from("ddl/OMOPCDM_postgresql_5.4_views.sql (stale)"),
            String::from("generated/gone.rs (stale)"),
            String::from("generated/person.rs"),
        ],
        paths
    );
    Ok(())
}
