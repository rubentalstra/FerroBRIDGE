use crate::v2::render::segment::render_segment;
use crate::v2::render::structure::render_structure;

/// The hand-written shapes the tables are statics of.
const MODEL: &str = include_str!("../../templates/hl7v2_model.rs");

/// A failure while rendering.
#[derive(Debug, thiserror::Error)]
pub enum RenderError {
    /// Writing to a string failed, which `String` never does.
    #[error("rendering failed")]
    Format(#[from] fmt::Error),
    /// Two definition ids map to one Rust name.
    #[error("{first} and {second} both render as {name}")]
    NameCollision {
        /// The first id.
        first: String,
        /// The second id.
        second: String,
        /// The shared name.
        name: String,
    },
    /// A structure names a segment the model does not hold.
    #[error("{structure} names segment {segment}, which the model does not hold")]
    MissingSegment {
        /// The structure id.
        structure: String,
        /// The segment id.
        segment: String,
    },
    /// A component names a data type the model does not hold.
    #[error("{component} names data type {data_type}, which the model does not hold")]
    MissingDataType {
        /// The component id.
        component: String,
        /// The data type code.
        data_type: String,
    },
    /// A message definition names a structure the model does not hold.
    #[error("{message} names structure {structure}, which the model does not hold")]
    MissingStructure {
        /// The message id.
        message: String,
        /// The structure id.
        structure: String,
    },
}

/// The banner every file of `hl7v2-types` generated from the v2.9.1
/// definitions starts with.
#[must_use]
pub fn banner(model: &Model) -> String {
    format!(
        "// @generated by fhir-codegen from HL7/v2ig {} input/sourceOfTruth. DO NOT EDIT.\n// Change the emitter (tools/fhir-codegen) and regenerate.\n{SPDX}",
        model.commit
    )
}

/// The banner of a file generated from both the v2.9.1 definitions and the
/// legacy tables: the crate root and the message index.
#[must_use]
pub fn joint_banner(model: &Model, legacy: &LegacyModel) -> String {
    format!(
        "// @generated by fhir-codegen from HL7/v2ig {} input/sourceOfTruth and {REPOSITORY} {} {TABLES_DIR}. DO NOT EDIT.\n// Change the emitter (tools/fhir-codegen) and regenerate.\n{SPDX}",
        model.commit, legacy.commit
    )
}

/// The banner every file under `legacy/` starts with.
#[must_use]
pub fn legacy_banner(legacy: &LegacyModel) -> String {
    format!(
        "// @generated by fhir-codegen from {REPOSITORY} {} {TABLES_DIR}. DO NOT EDIT.\n// Change the emitter (tools/fhir-codegen) and regenerate.\n{SPDX}",
        legacy.commit
    )
}

/// The module name of a legacy version: `2.5.1` is `v2_5_1`.
#[must_use]
pub fn version_module(version: &str) -> String {
    format!("v{}", version.replace('.', "_"))
}

/// The module name and static name of a definition id: `ORU_R01-A` renders
/// as the module `oru_r01_a` holding the static `ORU_R01_A`.
///
/// Every character outside `[A-Za-z0-9]` becomes `_`; the module name is the
/// result in lower case and the static in upper case. A module name that is a
/// device name Windows reserves for files (`CON` renders as `con`) takes a
/// trailing `_`, so the crate checks out and builds there: the `CON` segment
/// is the module `con_` holding the static `CON`. A module name that is a Rust
/// keyword takes the same trailing `_`: the `FN` data type is the module `fn_`.
#[must_use]
pub fn names(id: &str) -> (String, String) {
    let base: String = id
        .chars()
        .map(|ch| if ch.is_ascii_alphanumeric() { ch } else { '_' })
        .collect();
    let mut module = base.to_ascii_lowercase();
    if is_reserved_file_name(&module) || is_keyword(&module) {
        module.push('_');
    }
    (module, base.to_ascii_uppercase())
}

/// Whether Windows reserves `stem` as a device name, whatever the extension
/// (<https://learn.microsoft.com/en-us/windows/win32/fileio/naming-a-file>).
fn is_reserved_file_name(stem: &str) -> bool {
    match stem {
        "con" | "prn" | "aux" | "nul" => true,
        _ => stem
            .strip_prefix("com")
            .or_else(|| stem.strip_prefix("lpt"))
            .is_some_and(|digit| digit.len() == 1 && digit.bytes().all(|b| b.is_ascii_digit())),
    }
}

/// Every file of the generated crate, keyed by its path under `src/`.
///
/// # Errors
///
/// Returns [`RenderError`] when two ids share a Rust name, or a structure
/// names a segment, component or data type the model lacks.
pub fn render(
    model: &Model,
    legacy: &LegacyModel,
) -> Result<BTreeMap<String, String>, RenderError> {
    let banner = banner(model);
    let joint = joint_banner(model, legacy);
    let segment_names = module_names(model.segments.keys())?;
    let structure_names = module_names(model.structures.keys())?;
    let data_type_names = module_names(model.data_types.keys())?;
    let message_names = module_names(model.messages.keys())?;
    let mut files = BTreeMap::new();
    files.insert(String::from("lib.rs"), render_lib(&joint, model, legacy)?);
    files.insert(String::from("model.rs"), format!("{joint}{MODEL}"));
    files.insert(
        String::from("segment/mod.rs"),
        render_index(&banner, &segment_names, Index::Segment, None)?,
    );
    files.insert(
        String::from("structure/mod.rs"),
        render_index(&banner, &structure_names, Index::Structure, None)?,
    );
    files.insert(
        String::from("data_type/mod.rs"),
        render_index(&banner, &data_type_names, Index::DataType, None)?,
    );
    files.insert(
        String::from("message/mod.rs"),
        render_message_index(&joint, model, &message_names, legacy)?,
    );
    for (id, segment) in &model.segments {
        let (module, name) = names(id);
        files.insert(
            format!("segment/{module}.rs"),
            render_segment(&banner, &name, segment, &data_type_names, None)?,
        );
    }
    let current_segment = |id: &str| {
        segment_names
            .get(id)
            .map(|(module, name)| format!("segment::{module}::{name}"))
    };
    for (id, structure) in &model.structures {
        let (module, name) = names(id);
        files.insert(
            format!("structure/{module}.rs"),
            render_structure(&banner, &name, structure, &current_segment, true)?,
        );
    }
    render_legacy(legacy, &segment_names, &data_type_names, &mut files)?;
    for (code, data_type) in &model.data_types {
        let (module, name) = names(code);
        files.insert(
            format!("data_type/{module}.rs"),
            render_data_type(&banner, &name, data_type, &data_type_names)?,
        );
    }
    for (id, message) in &model.messages {
        let (module, name) = names(id);
        files.insert(
            format!("message/{module}.rs"),
            render_message(&banner, &name, message, &structure_names)?,
        );
    }
    Ok(files)
}

/// The module and static name of every id, refusing a collision; [`names`]
/// already gives a keyword its trailing `_`.
fn module_names<'a>(
    ids: impl Iterator<Item = &'a String>,
) -> Result<BTreeMap<String, (String, String)>, RenderError> {
    let mut out = BTreeMap::new();
    let mut taken: BTreeMap<String, String> = BTreeMap::new();
    for id in ids {
        let (module, name) = names(id);
        if let Some(first) = taken.insert(module.clone(), id.clone()) {
            return Err(RenderError::NameCollision {
                first,
                second: id.clone(),
                name: module,
            });
        }
        out.insert(id.clone(), (module, name));
    }
    Ok(out)
}

fn render_lib(banner: &str, model: &Model, legacy: &LegacyModel) -> Result<String, RenderError> {
    let mut out = String::from(banner);
    out.push_str(
        "//! The HL7 v2 message structures, segment fields, data types and message definitions, generated from the HL7 v2 definitions.\n//!\n//! `structure` holds every message structure of the definitions as a\n//! segment-group tree, `segment` every segment definition with its\n//! field table, the batch envelopes included, `data_type` every primitive and\n//! complex data type with its component table, and `message` every message\n//! definition with the structure its trigger event selects. `legacy` holds\n//! the message structures of each earlier version's tables, those the\n//! definitions no longer carry among them, and `message` indexes them by\n//! code, event and version. The shapes are in `model`. Every file is `@generated`\n//! by `fhir-codegen`; change the emitter and regenerate, never the output.\n",
    );
    writeln!(
        out,
        "//!\n//! The definitions are `HL7/v2ig` at commit `{}`, path `input/sourceOfTruth`:\n//! {} message structures, {} segments with {} fields, {} data types ({} primitive,\n//! {} complex with {} components) and {} message definitions.",
        model.commit,
        model.structures.len(),
        model.segments.len(),
        model.field_count(),
        model.data_types.len(),
        model.primitive_count(),
        model.data_types.len() - model.primitive_count(),
        model.component_count(),
        model.messages.len(),
    )?;
    writeln!(
        out,
        "//!\n//! The legacy tables are the NIST IGAMT export of HL7's v2 database,\n//! `{REPOSITORY}` at commit `{}`, path `{TABLES_DIR}`:\n//! {} message structures of {} structure codes over {} versions ({} of {} codes the\n//! definitions no longer carry), with {} trees of their own, {} linked to the identical\n//! v2.9.1 tree and {} to an earlier version's. The trees name {} segments of their own\n//! ({} fields), {} references linked to the agreeing v2.9.1 segment and {} to an earlier\n//! version's identical one, and {} legacy message entries index them.\n",
        legacy.commit,
        legacy.structure_count(),
        legacy.code_count(),
        legacy.versions.len(),
        legacy.withdrawn_count(),
        legacy.withdrawn_code_count(),
        legacy.tree_count(),
        legacy.current_tree_count(),
        legacy.inherited_tree_count(),
        legacy.segment_count(),
        legacy.field_count(),
        legacy.shared_count(),
        legacy.inherited_count(),
        legacy.messages.len(),
    )?;
    out.push_str(
        "pub mod data_type;\npub mod legacy;\npub mod message;\npub mod model;\npub mod segment;\npub mod structure;\n",
    );
    Ok(out)
}
