//! Rendering the lowered v2 tables to the source of `hl7v2-types`.
//!
//! One module per segment under `segment/`, per message structure under
//! `structure/`, per data type under `data_type/` and per message definition
//! under `message/`, each holding one `static`. A structure's tree refers to
//! the segment statics, a field and a component to the data type statics, and
//! a message definition to its structure, so each table is one step from the
//! entry that names it. Every file opens with the `@generated` banner.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::{self, Write};

use crate::naming::is_keyword;
use crate::render::SPDX;
use crate::v2::legacy::lower::{LegacyModel, LegacyVersion, Owner};
use crate::v2::legacy::source::{REPOSITORY, TABLES_DIR};
use crate::v2::lower::{
    Cardinality, Component, ConditionalCode, ConformanceLength, DataType, Field, GroupKind, Length,
    Message, MessageStatus, Model, Node, Optionality, Segment, SegmentStatus, StandardsStatus,
    Structure, Table,
};

/// The hand-written shapes the tables are statics of.
const MODEL: &str = include_str!("../templates/hl7v2_model.rs");

/// A failure while rendering.
#[derive(Debug, thiserror::Error)]
pub enum RenderError {
    /// Writing to a string failed, which `String` never does.
    #[error("rendering failed")]
    Format(#[from] fmt::Error),
    /// Two definition ids map to one Rust name.
    #[error("{first} and {second} both render as {name}")]
    NameCollision {
        /// The first id.
        first: String,
        /// The second id.
        second: String,
        /// The shared name.
        name: String,
    },
    /// A structure names a segment the model does not hold.
    #[error("{structure} names segment {segment}, which the model does not hold")]
    MissingSegment {
        /// The structure id.
        structure: String,
        /// The segment id.
        segment: String,
    },
    /// A component names a data type the model does not hold.
    #[error("{component} names data type {data_type}, which the model does not hold")]
    MissingDataType {
        /// The component id.
        component: String,
        /// The data type code.
        data_type: String,
    },
    /// A message definition names a structure the model does not hold.
    #[error("{message} names structure {structure}, which the model does not hold")]
    MissingStructure {
        /// The message id.
        message: String,
        /// The structure id.
        structure: String,
    },
}

/// The banner every file of `hl7v2-types` generated from the v2.9.1
/// definitions starts with.
#[must_use]
pub fn banner(model: &Model) -> String {
    format!(
        "// @generated by fhir-codegen from HL7/v2ig {} input/sourceOfTruth. DO NOT EDIT.\n// Change the emitter (tools/fhir-codegen) and regenerate.\n{SPDX}",
        model.commit
    )
}

/// The banner of a file generated from both the v2.9.1 definitions and the
/// legacy tables: the crate root and the message index.
#[must_use]
pub fn joint_banner(model: &Model, legacy: &LegacyModel) -> String {
    format!(
        "// @generated by fhir-codegen from HL7/v2ig {} input/sourceOfTruth and {REPOSITORY} {} {TABLES_DIR}. DO NOT EDIT.\n// Change the emitter (tools/fhir-codegen) and regenerate.\n{SPDX}",
        model.commit, legacy.commit
    )
}

/// The banner every file under `legacy/` starts with.
#[must_use]
pub fn legacy_banner(legacy: &LegacyModel) -> String {
    format!(
        "// @generated by fhir-codegen from {REPOSITORY} {} {TABLES_DIR}. DO NOT EDIT.\n// Change the emitter (tools/fhir-codegen) and regenerate.\n{SPDX}",
        legacy.commit
    )
}

/// The module name of a legacy version: `2.5.1` is `v2_5_1`.
#[must_use]
pub fn version_module(version: &str) -> String {
    format!("v{}", version.replace('.', "_"))
}

/// The module name and static name of a definition id: `ORU_R01-A` renders
/// as the module `oru_r01_a` holding the static `ORU_R01_A`.
///
/// Every character outside `[A-Za-z0-9]` becomes `_`; the module name is the
/// result in lower case and the static in upper case. A module name that is a
/// device name Windows reserves for files (`CON` renders as `con`) takes a
/// trailing `_`, so the crate checks out and builds there: the `CON` segment
/// is the module `con_` holding the static `CON`. A module name that is a Rust
/// keyword takes the same trailing `_`: the `FN` data type is the module `fn_`.
#[must_use]
pub fn names(id: &str) -> (String, String) {
    let base: String = id
        .chars()
        .map(|ch| if ch.is_ascii_alphanumeric() { ch } else { '_' })
        .collect();
    let mut module = base.to_ascii_lowercase();
    if is_reserved_file_name(&module) || is_keyword(&module) {
        module.push('_');
    }
    (module, base.to_ascii_uppercase())
}

/// Whether Windows reserves `stem` as a device name, whatever the extension
/// (<https://learn.microsoft.com/en-us/windows/win32/fileio/naming-a-file>).
fn is_reserved_file_name(stem: &str) -> bool {
    match stem {
        "con" | "prn" | "aux" | "nul" => true,
        _ => stem
            .strip_prefix("com")
            .or_else(|| stem.strip_prefix("lpt"))
            .is_some_and(|digit| digit.len() == 1 && digit.bytes().all(|b| b.is_ascii_digit())),
    }
}

/// Every file of the generated crate, keyed by its path under `src/`.
///
/// # Errors
///
/// Returns [`RenderError`] when two ids share a Rust name, or a structure
/// names a segment, component or data type the model lacks.
pub fn render(
    model: &Model,
    legacy: &LegacyModel,
) -> Result<BTreeMap<String, String>, RenderError> {
    let banner = banner(model);
    let joint = joint_banner(model, legacy);
    let segment_names = module_names(model.segments.keys())?;
    let structure_names = module_names(model.structures.keys())?;
    let data_type_names = module_names(model.data_types.keys())?;
    let message_names = module_names(model.messages.keys())?;
    let mut files = BTreeMap::new();
    files.insert(String::from("lib.rs"), render_lib(&joint, model, legacy)?);
    files.insert(String::from("model.rs"), format!("{joint}{MODEL}"));
    files.insert(
        String::from("segment/mod.rs"),
        render_index(&banner, &segment_names, Index::Segment, None)?,
    );
    files.insert(
        String::from("structure/mod.rs"),
        render_index(&banner, &structure_names, Index::Structure, None)?,
    );
    files.insert(
        String::from("data_type/mod.rs"),
        render_index(&banner, &data_type_names, Index::DataType, None)?,
    );
    files.insert(
        String::from("message/mod.rs"),
        render_message_index(&joint, model, &message_names, legacy)?,
    );
    for (id, segment) in &model.segments {
        let (module, name) = names(id);
        files.insert(
            format!("segment/{module}.rs"),
            render_segment(&banner, &name, segment, &data_type_names, None)?,
        );
    }
    let current_segment = |id: &str| {
        segment_names
            .get(id)
            .map(|(module, name)| format!("segment::{module}::{name}"))
    };
    for (id, structure) in &model.structures {
        let (module, name) = names(id);
        files.insert(
            format!("structure/{module}.rs"),
            render_structure(&banner, &name, structure, &current_segment, true)?,
        );
    }
    render_legacy(legacy, &segment_names, &data_type_names, &mut files)?;
    for (code, data_type) in &model.data_types {
        let (module, name) = names(code);
        files.insert(
            format!("data_type/{module}.rs"),
            render_data_type(&banner, &name, data_type, &data_type_names)?,
        );
    }
    for (id, message) in &model.messages {
        let (module, name) = names(id);
        files.insert(
            format!("message/{module}.rs"),
            render_message(&banner, &name, message, &structure_names)?,
        );
    }
    Ok(files)
}

/// The module and static name of every id, refusing a collision; [`names`]
/// already gives a keyword its trailing `_`.
fn module_names<'a>(
    ids: impl Iterator<Item = &'a String>,
) -> Result<BTreeMap<String, (String, String)>, RenderError> {
    let mut out = BTreeMap::new();
    let mut taken: BTreeMap<String, String> = BTreeMap::new();
    for id in ids {
        let (module, name) = names(id);
        if let Some(first) = taken.insert(module.clone(), id.clone()) {
            return Err(RenderError::NameCollision {
                first,
                second: id.clone(),
                name: module,
            });
        }
        out.insert(id.clone(), (module, name));
    }
    Ok(out)
}

fn render_lib(banner: &str, model: &Model, legacy: &LegacyModel) -> Result<String, RenderError> {
    let mut out = String::from(banner);
    out.push_str(
        "//! The HL7 v2 message structures, segment fields, data types and message definitions, generated from the HL7 v2 definitions.\n//!\n//! `structure` holds every message structure of the definitions as a\n//! segment-group tree, `segment` every segment definition with its\n//! field table, the batch envelopes included, `data_type` every primitive and\n//! complex data type with its component table, and `message` every message\n//! definition with the structure its trigger event selects. `legacy` holds\n//! the message structures of each earlier version's tables, those the\n//! definitions no longer carry among them, and `message` indexes them by\n//! code, event and version. The shapes are in `model`. Every file is `@generated`\n//! by `fhir-codegen`; change the emitter and regenerate, never the output.\n",
    );
    writeln!(
        out,
        "//!\n//! The definitions are `HL7/v2ig` at commit `{}`, path `input/sourceOfTruth`:\n//! {} message structures, {} segments with {} fields, {} data types ({} primitive,\n//! {} complex with {} components) and {} message definitions.",
        model.commit,
        model.structures.len(),
        model.segments.len(),
        model.field_count(),
        model.data_types.len(),
        model.primitive_count(),
        model.data_types.len() - model.primitive_count(),
        model.component_count(),
        model.messages.len(),
    )?;
    writeln!(
        out,
        "//!\n//! The legacy tables are the NIST IGAMT export of HL7's v2 database,\n//! `{REPOSITORY}` at commit `{}`, path `{TABLES_DIR}`:\n//! {} message structures of {} structure codes over {} versions ({} of {} codes the\n//! definitions no longer carry), with {} trees of their own, {} linked to the identical\n//! v2.9.1 tree and {} to an earlier version's. The trees name {} segments of their own\n//! ({} fields), {} references linked to the agreeing v2.9.1 segment and {} to an earlier\n//! version's identical one, and {} legacy message entries index them.\n",
        legacy.commit,
        legacy.structure_count(),
        legacy.code_count(),
        legacy.versions.len(),
        legacy.withdrawn_count(),
        legacy.withdrawn_code_count(),
        legacy.tree_count(),
        legacy.current_tree_count(),
        legacy.inherited_tree_count(),
        legacy.segment_count(),
        legacy.field_count(),
        legacy.shared_count(),
        legacy.inherited_count(),
        legacy.messages.len(),
    )?;
    out.push_str(
        "pub mod data_type;\npub mod legacy;\npub mod message;\npub mod model;\npub mod segment;\npub mod structure;\n",
    );
    Ok(out)
}

/// The segment and data type modules of one legacy version.
fn render_legacy_segments(
    banner: &str,
    version: &LegacyVersion,
    module: &str,
    segment_names: &BTreeMap<String, (String, String)>,
    data_types: &BTreeMap<String, (String, String)>,
    files: &mut BTreeMap<String, String>,
) -> Result<(), RenderError> {
    if !version.segments.is_empty() {
        let segment_doc = format!(
            "The segments of the {} tables that no v2.9.1 or earlier `static` carries, one module each.",
            version.version
        );
        files.insert(
            format!("legacy/{module}/segment/mod.rs"),
            render_index(
                banner,
                segment_names,
                Index::Segment,
                Some((&segment_doc, "ORC")),
            )?,
        );
    }
    let legacy_types = module_names(version.data_types.keys())?;
    if !version.data_types.is_empty() {
        files.insert(
            format!("legacy/{module}/data_type.rs"),
            render_legacy_data_types(banner, version, &legacy_types)?,
        );
    }
    let tables = LegacyTables {
        version: &version.version,
        module,
        data_types: &legacy_types,
    };
    for (id, segment) in &version.segments {
        let (file, name) = names(id);
        files.insert(
            format!("legacy/{module}/segment/{file}.rs"),
            render_segment(banner, &name, segment, data_types, Some(&tables))?,
        );
    }
    Ok(())
}

/// Every file under `legacy/`: the version index, and per version its
/// structure, segment and data type modules.
fn render_legacy(
    legacy: &LegacyModel,
    current_segments: &BTreeMap<String, (String, String)>,
    data_types: &BTreeMap<String, (String, String)>,
    files: &mut BTreeMap<String, String>,
) -> Result<(), RenderError> {
    let banner = legacy_banner(legacy);
    let mut index: Vec<(&str, usize, String)> = Vec::new();
    for (order, version) in legacy.versions.iter().enumerate() {
        let module = version_module(&version.version);
        let structure_names = module_names(version.structures.keys())?;
        let segment_names = module_names(version.segments.keys())?;
        files.insert(
            format!("legacy/{module}/mod.rs"),
            render_version_module(&banner, version)?,
        );
        let structure_doc = format!(
            "The legacy message structures of the {} tables, one module each.",
            version.version
        );
        files.insert(
            format!("legacy/{module}/structure/mod.rs"),
            render_index(
                &banner,
                &structure_names,
                Index::Structure,
                Some((&structure_doc, "ORM_O01")),
            )?,
        );
        render_legacy_segments(&banner, version, &module, &segment_names, data_types, files)?;
        let resolve = |id: &str| match version.links.get(id) {
            Some(Owner::Current) => current_segments
                .get(id)
                .map(|(file, name)| format!("crate::segment::{file}::{name}")),
            Some(Owner::Version(owner)) => {
                let (file, name) = names(id);
                Some(format!(
                    "crate::legacy::{}::segment::{file}::{name}",
                    version_module(owner)
                ))
            }
            None => segment_names
                .get(id)
                .map(|(file, name)| format!("crate::legacy::{module}::segment::{file}::{name}")),
        };
        for (id, structure) in &version.structures {
            let (file, name) = names(id);
            let text = match version.trees.get(id) {
                None => render_structure(&banner, &name, structure, &resolve, false)?,
                Some(owner) => render_linked_structure(&banner, &name, structure, owner)?,
            };
            files.insert(format!("legacy/{module}/structure/{file}.rs"), text);
            index.push((
                id.as_str(),
                order,
                format!("{module}::structure::{file}::{name}"),
            ));
        }
    }
    index.sort_by(|left, right| (left.0, left.1).cmp(&(right.0, right.1)));
    let mut out = banner;
    out.push_str(
        "//! The message structures of the tables of each earlier HL7 v2 version, one\n//! module per version, those the v2.9.1 definitions no longer carry among them.\n//!\n//! A version module holds `structure`, one module per structure with its\n//! tree, and `segment` for each segment no other `static` carries. A tree\n//! links a segment whose field table agrees with the v2.9.1 one to the v2.9.1\n//! `static`, and one identical to an earlier version's to that version's; a\n//! structure whose tree is identical to the v2.9.1 tree or to an earlier\n//! version's links its nodes to that tree. `data_type` holds the data type\n//! codes the version's own segments name, each with the base type a\n//! version-specific code stands for. Each [`crate::model::Structure`] here\n//! carries its version and, for a structure the v2.9.1 definitions no longer\n//! carry, the version it is withdrawn as of.\n\n",
    );
    for version in &legacy.versions {
        writeln!(out, "pub mod {};", version_module(&version.version))?;
    }
    writeln!(
        out,
        "\n/// Every legacy message structure, in `(id, version)` order with the\n/// versions ordered numerically.\npub static STRUCTURES: [&crate::model::Structure; {}] = [",
        index.len()
    )?;
    for (_, _, path) in &index {
        writeln!(out, "    &{path},")?;
    }
    out.push_str(
        "];\n\n/// Returns every version's structure whose id is `id`, for example\n/// `ORM_O01`, in version order.\n#[must_use]\npub fn versions(id: &str) -> &'static [&'static crate::model::Structure] {\n    let start = STRUCTURES.partition_point(|entry| entry.id < id);\n    let end = STRUCTURES.partition_point(|entry| entry.id <= id);\n    STRUCTURES.get(start..end).unwrap_or(&[])\n}\n\n/// Returns the structure `id` of the tables of `version`, for example\n/// `ORM_O01` of `2.5.1`.\n#[must_use]\npub fn find(id: &str, version: &str) -> Option<&'static crate::model::Structure> {\n    versions(id)\n        .iter()\n        .copied()\n        .find(|entry| entry.version == version)\n}\n",
    );
    files.insert(String::from("legacy/mod.rs"), out);
    Ok(())
}

fn render_version_module(banner: &str, version: &LegacyVersion) -> Result<String, RenderError> {
    let mut out = String::from(banner);
    write!(
        out,
        "//! The message structures of the {} tables, and the segments they name\n//! that no v2.9.1 or earlier `static` carries.\n\n",
        version.version
    )?;
    if !version.data_types.is_empty() {
        out.push_str("pub mod data_type;\n");
    }
    if !version.segments.is_empty() {
        out.push_str("pub mod segment;\n");
    }
    out.push_str("pub mod structure;\n");
    Ok(out)
}

/// The data type codes of one legacy version, from a segment module.
#[derive(Debug, Clone, Copy)]
struct LegacyTables<'a> {
    version: &'a str,
    module: &'a str,
    data_types: &'a BTreeMap<String, (String, String)>,
}

/// The `data_type` module of a legacy version: one `static` per data type
/// code its segments' fields name.
fn render_legacy_data_types(
    banner: &str,
    version: &LegacyVersion,
    names: &BTreeMap<String, (String, String)>,
) -> Result<String, RenderError> {
    let mut out = String::from(banner);
    let uses = if version
        .data_types
        .values()
        .any(|data_type| data_type.base.is_some())
    {
        "use crate::model::{LegacyBase, LegacyDataType};\n"
    } else {
        "use crate::model::LegacyDataType;\n"
    };
    write!(
        out,
        "//! The data type codes the fields of the {} tables name, with the base\n//! type each version-specific code stands for.\n\n{uses}",
        version.version
    )?;
    for ((code, data_type), (_, name)) in version.data_types.iter().zip(names.values()) {
        let base = data_type.base.as_ref().map_or_else(
            || String::from("None"),
            |base| {
                let table = base
                    .table
                    .as_ref()
                    .map_or_else(|| String::from("None"), |table| format!("Some({table:?})"));
                format!(
                    "Some(LegacyBase {{ code: {:?}, table: {table} }})",
                    base.code
                )
            },
        );
        write!(
            out,
            "\n/// The `{code}` data type code of the {} tables.\npub static {name}: LegacyDataType = LegacyDataType {{\n    code: {code:?},\n    version: {:?},\n    name: {:?},\n    base: {base},\n}};\n",
            version.version, version.version, data_type.name
        )?;
    }
    Ok(out)
}

#[derive(Debug, Clone, Copy)]
enum Index {
    Segment,
    Structure,
    DataType,
}

fn render_index(
    banner: &str,
    names: &BTreeMap<String, (String, String)>,
    index: Index,
    legacy: Option<(&str, &str)>,
) -> Result<String, RenderError> {
    let (doc, kind, list, noun, key, example) = match index {
        Index::Segment => (
            "Every segment definition, one module each.",
            "Segment",
            "SEGMENTS",
            "segment",
            "definition id",
            "OBX",
        ),
        Index::Structure => (
            "Every message structure of the HL7 v2 definitions, one module each.",
            "Structure",
            "STRUCTURES",
            "message structure",
            "definition id",
            "ORU_R01-A",
        ),
        Index::DataType => (
            "Every primitive and complex data type of the HL7 v2 definitions, one module each.",
            "DataType",
            "DATA_TYPES",
            "data type",
            "code",
            "CX",
        ),
    };
    let field = match index {
        Index::Segment | Index::Structure => "id",
        Index::DataType => "code",
    };
    let (doc, example) = legacy.unwrap_or((doc, example));
    let mut out = String::from(banner);
    writeln!(out, "//! {doc}\n")?;
    for (module, _) in names.values() {
        writeln!(out, "pub mod {module};")?;
    }
    writeln!(
        out,
        "\n/// Every {noun}, in definition id order.\npub static {list}: [&crate::model::{kind}; {}] = [",
        names.len()
    )?;
    for (module, name) in names.values() {
        writeln!(out, "    &{module}::{name},")?;
    }
    writeln!(
        out,
        "];\n\n/// Returns the {noun} whose {key} is `{field}`, for example `{example}`.\n#[must_use]\npub fn find({field}: &str) -> Option<&'static crate::model::{kind}> {{\n    match {list}.binary_search_by(|entry| entry.{field}.cmp({field})) {{\n        Ok(index) => {list}.get(index).copied(),\n        Err(_) => None,\n    }}\n}}"
    )?;
    Ok(out)
}

/// The message index: every message definition in `(code, event)` order.
fn render_message_index(
    banner: &str,
    model: &Model,
    names: &BTreeMap<String, (String, String)>,
    legacy: &LegacyModel,
) -> Result<String, RenderError> {
    let mut out = String::from(banner);
    writeln!(
        out,
        "//! Every message definition of the HL7 v2 definitions, one module each,\n//! and the legacy message structures by code, event and version.\n"
    )?;
    for (module, _) in names.values() {
        writeln!(out, "pub mod {module};")?;
    }
    let mut ordered: Vec<(&str, &str, &(String, String))> = Vec::with_capacity(names.len());
    for (id, message) in &model.messages {
        if let Some(entry) = names.get(id) {
            ordered.push((&message.code, &message.event, entry));
        }
    }
    ordered.sort_by(|left, right| (left.0, left.1).cmp(&(right.0, right.1)));
    writeln!(
        out,
        "\n/// Every message definition, in `(code, event)` order.\npub static MESSAGES: [&crate::model::Message; {}] = [",
        ordered.len()
    )?;
    for (_, _, (module, name)) in &ordered {
        writeln!(out, "    &{module}::{name},")?;
    }
    writeln!(
        out,
        "];\n\n/// Returns the message definition sent as `code^event` (`MSH-9.1` and\n/// `MSH-9.2`), for example `ORU` and `R01`.\n#[must_use]\npub fn find(code: &str, event: &str) -> Option<&'static crate::model::Message> {{\n    match MESSAGES.binary_search_by(|entry| (entry.code, entry.event).cmp(&(code, event))) {{\n        Ok(index) => MESSAGES.get(index).copied(),\n        Err(_) => None,\n    }}\n}}"
    )?;
    writeln!(
        out,
        "\n/// Every legacy message structure by the message code and trigger event its\n/// tables give it, in `(code, event, version)` order with the versions\n/// ordered numerically.\npub static LEGACY: [crate::model::LegacyMessage; {}] = [",
        legacy.messages.len()
    )?;
    for entry in &legacy.messages {
        let Some(version) = legacy
            .versions
            .iter()
            .find(|version| version.version == entry.version)
        else {
            return Err(RenderError::MissingStructure {
                message: format!("{}^{} {}", entry.code, entry.event, entry.version),
                structure: entry.structure.clone(),
            });
        };
        if !version.structures.contains_key(&entry.structure) {
            return Err(RenderError::MissingStructure {
                message: format!("{}^{} {}", entry.code, entry.event, entry.version),
                structure: entry.structure.clone(),
            });
        }
        let (file, name) = crate::v2::render::names(&entry.structure);
        writeln!(
            out,
            "    crate::model::LegacyMessage {{ code: {:?}, event: {:?}, version: {:?}, structure: &crate::legacy::{}::structure::{file}::{name} }},",
            entry.code,
            entry.event,
            entry.version,
            version_module(&entry.version)
        )?;
    }
    out.push_str(
        "];\n\n/// Returns the legacy entries sent as `code^event` (`MSH-9.1` and\n/// `MSH-9.2`), for example `ORM` and `O01`, one per version in version order.\n#[must_use]\npub fn legacy(code: &str, event: &str) -> &'static [crate::model::LegacyMessage] {\n    let start = LEGACY.partition_point(|entry| (entry.code, entry.event) < (code, event));\n    let end = LEGACY.partition_point(|entry| (entry.code, entry.event) <= (code, event));\n    LEGACY.get(start..end).unwrap_or(&[])\n}\n\n/// Returns the legacy entry sent as `code^event` in the tables of `version`\n/// (`MSH-12`), for example `ORM`, `O01` and `2.5.1`.\n#[must_use]\npub fn find_legacy(\n    code: &str,\n    event: &str,\n    version: &str,\n) -> Option<&'static crate::model::LegacyMessage> {\n    legacy(code, event)\n        .iter()\n        .find(|entry| entry.version == version)\n}\n",
    );
    Ok(out)
}

fn cardinality(cardinality: Cardinality) -> String {
    let max = match cardinality.max {
        Some(max) => format!("Max::Bounded({max})"),
        None => String::from("Max::Unbounded"),
    };
    format!("Cardinality {{ min: {}, max: {max} }}", cardinality.min)
}

fn optionality(value: Optionality, uses: &mut BTreeSet<&'static str>) -> String {
    let code = |code: ConditionalCode| match code {
        ConditionalCode::R => "ConditionalCode::R",
        ConditionalCode::Re => "ConditionalCode::Re",
        ConditionalCode::O => "ConditionalCode::O",
        ConditionalCode::X => "ConditionalCode::X",
    };
    match value {
        Optionality::R => String::from("Optionality::R"),
        Optionality::Re => String::from("Optionality::Re"),
        Optionality::O => String::from("Optionality::O"),
        Optionality::C => String::from("Optionality::C"),
        Optionality::Conditional(first, second) => {
            uses.insert("ConditionalCode");
            format!(
                "Optionality::Conditional {{ first: {}, second: {} }}",
                code(first),
                code(second)
            )
        }
        Optionality::X => String::from("Optionality::X"),
        Optionality::B => String::from("Optionality::B"),
        Optionality::W => String::from("Optionality::W"),
        Optionality::Na => String::from("Optionality::Na"),
        Optionality::Unstated => String::from("Optionality::Unstated"),
    }
}

fn optional_u32(value: Option<u32>) -> String {
    value.map_or_else(|| String::from("None"), |value| format!("Some({value})"))
}

fn length(value: Option<Length>, uses: &mut BTreeSet<&'static str>) -> String {
    value.map_or_else(
        || String::from("None"),
        |length| {
            uses.insert("Length");
            format!(
                "Some(Length {{ min: {}, max: {} }})",
                length.min,
                optional_u32(length.max)
            )
        },
    )
}

fn conformance_length(
    value: Option<ConformanceLength>,
    uses: &mut BTreeSet<&'static str>,
) -> String {
    value.map_or_else(
        || String::from("None"),
        |value| {
            uses.insert("ConformanceLength");
            let no_truncate = value
                .no_truncate
                .map_or_else(|| String::from("None"), |flag| format!("Some({flag})"));
            format!(
                "Some(ConformanceLength {{ length: {}, no_truncate: {no_truncate} }})",
                optional_u32(value.length)
            )
        },
    )
}

fn table(value: Option<&Table>, uses: &mut BTreeSet<&'static str>) -> String {
    value.map_or_else(
        || String::from("None"),
        |table| {
            uses.insert("Table");
            format!(
                "Some(Table {{ id: {:?}, value_set: {:?} }})",
                table.id, table.value_set
            )
        },
    )
}

/// The path of the data type static `code` names, from a sibling module.
fn data_type_path(code: &str, data_types: &BTreeMap<String, (String, String)>) -> Option<String> {
    data_types
        .get(code)
        .map(|(module, name)| format!("&data_type::{module}::{name}"))
}

fn field(
    field: &Field,
    data_types: &BTreeMap<String, (String, String)>,
    legacy: Option<&LegacyTables<'_>>,
    uses: &mut BTreeSet<&'static str>,
) -> Result<String, RenderError> {
    let data_type = match (&field.data_type, legacy) {
        (None, _) => String::from("None"),
        (Some(code), Some(tables)) => {
            uses.insert("DataTypeRef");
            let Some((_, name)) = tables.data_types.get(code) else {
                return Err(RenderError::MissingDataType {
                    component: field.id.clone(),
                    data_type: code.clone(),
                });
            };
            format!(
                "Some(DataTypeRef::Legacy(&crate::legacy::{}::data_type::{name}))",
                tables.module
            )
        }
        (Some(code), None) => {
            uses.insert("DataTypeRef");
            match data_type_path(code, data_types) {
                Some(path) => {
                    uses.insert("data_type");
                    format!("Some(DataTypeRef::Defined({path}))")
                }
                None => format!("Some(DataTypeRef::Undefined({code:?}))"),
            }
        }
    };
    let length = length(field.length, uses);
    let conformance_length = conformance_length(field.conformance_length, uses);
    let table = table(field.table.as_ref(), uses);
    let standards_status = field.standards_status.map_or_else(
        || String::from("None"),
        |status| {
            uses.insert("StandardsStatus");
            match status {
                StandardsStatus::Deprecated => String::from("Some(StandardsStatus::Deprecated)"),
                StandardsStatus::Withdrawn => String::from("Some(StandardsStatus::Withdrawn)"),
            }
        },
    );
    Ok(format!(
        "Field {{ id: {:?}, position: {}, name: {:?}, data_type: {data_type}, cardinality: {}, optionality: {}, length: {length}, conformance_length: {conformance_length}, table: {table}, standards_status: {standards_status} }}",
        field.id,
        field.position,
        field.name,
        cardinality(field.cardinality),
        optionality(field.optionality, uses),
    ))
}

/// The `use` lines for `uses`: the model shapes, and the `data_type`
/// module when a static names one.
fn uses_line(uses: &BTreeSet<&'static str>) -> String {
    let names: Vec<&str> = uses
        .iter()
        .copied()
        .filter(|name| *name != "data_type")
        .collect();
    let mut out = format!("use crate::model::{{{}}};\n", names.join(", "));
    if uses.contains("data_type") {
        out.push_str("use crate::data_type;\n");
    }
    out
}

fn render_segment(
    banner: &str,
    name: &str,
    segment: &Segment,
    data_types: &BTreeMap<String, (String, String)>,
    legacy: Option<&LegacyTables<'_>>,
) -> Result<String, RenderError> {
    let mut uses: BTreeSet<&'static str> = ["Segment"].into();
    let mut fields = String::new();
    for entry in &segment.fields {
        uses.extend(["Cardinality", "Field", "Max", "Optionality"]);
        writeln!(
            fields,
            "        {},",
            field(entry, data_types, legacy, &mut uses)?
        )?;
    }
    let legacy = legacy.map(|tables| tables.version);
    let mut out = String::from(banner);
    writeln!(
        out,
        "//! The `{}` segment: {}.\n",
        segment.id,
        segment.name.trim_end_matches('.')
    )?;
    out.push_str(&uses_line(&uses));
    let (doc, url) = match (legacy, &segment.url) {
        (Some(version), _) => (
            format!("The `{}` segment of the {version} tables.", segment.id),
            String::from("None"),
        ),
        (None, Some(url)) => (
            format!("The `{}` segment definition, `{url}`.", segment.id),
            format!("Some({url:?})"),
        ),
        (None, None) => (
            format!("The `{}` segment definition.", segment.id),
            String::from("None"),
        ),
    };
    writeln!(
        out,
        "\n/// {doc}\npub static {name}: Segment = Segment {{\n    id: {:?},\n    url: {url},\n    name: {:?},\n    fields: &[\n{fields}    ],\n}};",
        segment.id, segment.name
    )?;
    Ok(out)
}

/// Resolves a segment id to the path of its `static`, from a structure module.
type SegmentPath<'a> = &'a dyn Fn(&str) -> Option<String>;

struct TreeWriter<'a> {
    structure: &'a str,
    segments: SegmentPath<'a>,
    uses: BTreeSet<&'static str>,
}

impl TreeWriter<'_> {
    fn nodes(&mut self, nodes: &[Node], out: &mut String) -> Result<(), RenderError> {
        out.push_str("&[");
        for node in nodes {
            self.node(node, out)?;
            out.push(',');
        }
        out.push(']');
        Ok(())
    }

    fn node(&mut self, node: &Node, out: &mut String) -> Result<(), RenderError> {
        self.uses.extend(["Cardinality", "Max", "Node"]);
        match node {
            Node::Segment {
                id,
                position,
                segment,
                cardinality: count,
                status,
            } => {
                self.uses.insert("SegmentRef");
                let Some(path) = (self.segments)(segment) else {
                    return Err(RenderError::MissingSegment {
                        structure: self.structure.to_owned(),
                        segment: segment.clone(),
                    });
                };
                let status = match status {
                    None => "None",
                    Some(SegmentStatus::A) => "Some(SegmentStatus::A)",
                    Some(SegmentStatus::B) => "Some(SegmentStatus::B)",
                    Some(SegmentStatus::D) => "Some(SegmentStatus::D)",
                };
                if status != "None" {
                    self.uses.insert("SegmentStatus");
                }
                write!(
                    out,
                    "Node::Segment(SegmentRef {{ id: {id:?}, position: {position}, segment: &{path}, cardinality: {}, status: {status} }})",
                    cardinality(*count)
                )?;
            }
            Node::Group {
                id,
                position,
                name,
                cardinality: count,
                kind,
                children,
            } => {
                self.uses.insert("Group");
                self.uses.insert("GroupKind");
                let kind = match kind {
                    GroupKind::Sequence => "GroupKind::Sequence",
                    GroupKind::Choice => "GroupKind::Choice",
                };
                write!(
                    out,
                    "Node::Group(Group {{ id: {id:?}, position: {position}, name: {name:?}, cardinality: {}, kind: {kind}, children: ",
                    cardinality(*count)
                )?;
                self.nodes(children, out)?;
                out.push_str(" })");
            }
            Node::Placeholder {
                id,
                position,
                cardinality: count,
            } => {
                self.uses.insert("Placeholder");
                write!(
                    out,
                    "Node::Placeholder(Placeholder {{ id: {id:?}, position: {position}, cardinality: {} }})",
                    cardinality(*count)
                )?;
            }
        }
        Ok(())
    }
}

fn render_structure(
    banner: &str,
    name: &str,
    structure: &Structure,
    segments: SegmentPath<'_>,
    import_segment: bool,
) -> Result<String, RenderError> {
    let mut writer = TreeWriter {
        structure: &structure.id,
        segments,
        uses: ["Node", "Structure"].into(),
    };
    let mut tree = String::from("[");
    for node in &structure.nodes {
        writer.node(node, &mut tree)?;
        tree.push(',');
    }
    tree.push(']');
    let mut out = String::from(banner);
    let heading = structure_heading(structure);
    writeln!(out, "//! {heading}.\n")?;
    out.push_str(&uses_line(&writer.uses));
    if import_segment && writer.uses.contains("SegmentRef") {
        out.push_str("use crate::segment;\n");
    }
    let (doc, url) = match &structure.url {
        Some(url) => (
            format!(
                "The `{}` message structure definition, `{url}`.",
                structure.id
            ),
            format!("Some({url:?})"),
        ),
        None => (format!("{heading}."), String::from("None")),
    };
    let withdrawn = structure.withdrawn_as_of.as_ref().map_or_else(
        || String::from("None"),
        |version| format!("Some({version:?})"),
    );
    writeln!(
        out,
        "\n/// The top-level nodes of [`{name}`], one `static` so a structure with the same tree links to it.\npub static {name}_NODES: [Node; {}] = {tree};\n\n/// {doc}\npub static {name}: Structure = Structure {{\n    id: {:?},\n    url: {url},\n    version: {:?},\n    withdrawn_as_of: {withdrawn},\n    nodes: &{name}_NODES,\n}};",
        structure.nodes.len(),
        structure.id,
        structure.version
    )?;
    Ok(out)
}

/// The heading of a structure's module and `static`.
fn structure_heading(structure: &Structure) -> String {
    match (&structure.withdrawn_as_of, &structure.url) {
        (Some(withdrawn), _) => format!(
            "The `{}` message structure of the {} tables, withdrawn as of {withdrawn}",
            structure.id, structure.version
        ),
        (None, None) => format!(
            "The `{}` message structure of the {} tables",
            structure.id, structure.version
        ),
        (None, Some(_)) => format!("The `{}` message structure", structure.id),
    }
}

/// A structure of a version whose tree is identical to the tree `owner`
/// holds, and links to it.
fn render_linked_structure(
    banner: &str,
    name: &str,
    structure: &Structure,
    owner: &Owner,
) -> Result<String, RenderError> {
    let (file, _) = names(&structure.id);
    let (owner, from) = match owner {
        Owner::Current => (
            format!("crate::structure::{file}::{name}"),
            String::from("v2.9.1 definitions"),
        ),
        Owner::Version(version) => (
            format!(
                "crate::legacy::{}::structure::{file}::{name}",
                version_module(version)
            ),
            format!("{version} tables"),
        ),
    };
    let heading = structure_heading(structure);
    let withdrawn = structure.withdrawn_as_of.as_ref().map_or_else(
        || String::from("None"),
        |version| format!("Some({version:?})"),
    );
    let mut out = String::from(banner);
    writeln!(
        out,
        "//! {heading}.\n//!\n//! The tables give it the tree of the {from}, which it links to.\n\nuse crate::model::Structure;\n\n/// {heading}.\npub static {name}: Structure = Structure {{\n    id: {:?},\n    url: None,\n    version: {:?},\n    withdrawn_as_of: {withdrawn},\n    nodes: &{owner}_NODES,\n}};",
        structure.id, structure.version
    )?;
    Ok(out)
}

fn component(
    component: &Component,
    data_types: &BTreeMap<String, (String, String)>,
    uses: &mut BTreeSet<&'static str>,
) -> Result<String, RenderError> {
    let data_type = match &component.data_type {
        None => String::from("None"),
        Some(code) => {
            let Some(path) = data_type_path(code, data_types) else {
                return Err(RenderError::MissingDataType {
                    component: component.id.clone(),
                    data_type: code.clone(),
                });
            };
            uses.insert("data_type");
            format!("Some({path})")
        }
    };
    let count = component.cardinality.map_or_else(
        || String::from("None"),
        |count| {
            uses.extend(["Cardinality", "Max"]);
            format!("Some({})", cardinality(count))
        },
    );
    let length = length(component.length, uses);
    let conformance_length = conformance_length(component.conformance_length, uses);
    let table = table(component.table.as_ref(), uses);
    Ok(format!(
        "Component {{ id: {:?}, position: {}, name: {:?}, data_type: {data_type}, cardinality: {count}, optionality: {}, length: {length}, conformance_length: {conformance_length}, table: {table} }}",
        component.id,
        component.position,
        component.name,
        optionality(component.optionality, uses),
    ))
}

fn render_data_type(
    banner: &str,
    name: &str,
    data_type: &DataType,
    data_types: &BTreeMap<String, (String, String)>,
) -> Result<String, RenderError> {
    let mut uses: BTreeSet<&'static str> = ["DataType"].into();
    let mut components = String::new();
    for entry in &data_type.components {
        uses.extend(["Component", "Optionality"]);
        writeln!(
            components,
            "        {},",
            component(entry, data_types, &mut uses)?
        )?;
    }
    let kind = if data_type.components.is_empty() {
        "primitive"
    } else {
        "complex"
    };
    let mut out = String::from(banner);
    writeln!(
        out,
        "//! The `{}` {kind} data type: {}.\n",
        data_type.code,
        data_type.name.trim_end_matches('.')
    )?;
    out.push_str(&uses_line(&uses));
    let components = if components.is_empty() {
        String::from("&[]")
    } else {
        format!("&[\n{components}    ]")
    };
    writeln!(
        out,
        "\n/// The `{}` data type definition, `{}`.\npub static {name}: DataType = DataType {{\n    code: {:?},\n    url: {:?},\n    name: {:?},\n    components: {components},\n}};",
        data_type.code, data_type.url, data_type.code, data_type.url, data_type.name
    )?;
    Ok(out)
}

fn render_message(
    banner: &str,
    name: &str,
    message: &Message,
    structures: &BTreeMap<String, (String, String)>,
) -> Result<String, RenderError> {
    let structure = match &message.structure {
        None => String::from("None"),
        Some(id) => {
            let Some((module, static_name)) = structures.get(id) else {
                return Err(RenderError::MissingStructure {
                    message: message.id.clone(),
                    structure: id.clone(),
                });
            };
            format!("Some(&structure::{module}::{static_name})")
        }
    };
    let status = match message.status {
        MessageStatus::Active => "MessageStatus::Active",
        MessageStatus::Withdrawn => "MessageStatus::Withdrawn",
    };
    let mut out = String::from(banner);
    writeln!(
        out,
        "//! The `{}^{}` message definition.\n",
        message.code, message.event
    )?;
    out.push_str("use crate::model::{Message, MessageStatus};\n");
    if message.structure.is_some() {
        out.push_str("use crate::structure;\n");
    }
    writeln!(
        out,
        "\n/// The `{}` message definition, `{}`.\npub static {name}: Message = Message {{\n    id: {:?},\n    url: {:?},\n    code: {:?},\n    event: {:?},\n    structure: {structure},\n    status: {status},\n}};",
        message.id, message.url, message.id, message.url, message.code, message.event
    )?;
    Ok(out)
}
